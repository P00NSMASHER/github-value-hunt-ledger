def snapshot(max_labs: int=14) -> dict:
    with tempfile.TemporaryDirectory(prefix="retally-phase4-research-only-") as temp:
        rec,book=rating_fixture()
        store=funded_store(temp)
        a, fees=assertions_and_fees()
        result=execute_all_labs(record=rec,authority_book=book,store=store,
                                assertions=a,fee_events=fees,verifier=verifier(),
                                contingency=scenario(),max_labs=max_labs)
        campaign=conduct_experiments(register=load_findings(),
            ledger_path=Path(temp)/"phase4_campaign.sqlite3",max_experiments=4,
            record=rec,authority_book=book,store=store,assertions=a,fee_events=fees,
            verifier=verifier(),contingency=scenario())
        result["experiment_campaign"]=campaign
        result["research_intelligence"]=campaign_brief(as_of=date.today())
        proof, decisions=run_mission(as_of=date.today())
        result["research_evidence_fidelity"]=proof
        result["opposition_register"]=decisions
        result["source_review_queue"]=build_refresh_queue(
            registry=campaign_registry(as_of=date.today()),
            proof=proof, decisions=decisions, as_of=date.today()
        )
        result["validation_protocols"]=build_protocol_report(
            as_of=date.today(), decisions=decisions
        )
        result["synthetic_rehearsals"]=run_rehearsal(
            as_of=date.today(), protocol_report=result["validation_protocols"]
        )
        result["freight_data_readiness"]=build_readiness(
            as_of=date.today(), protocols=result["validation_protocols"]
        )
        result["invoice_ground_truth"]=run_ground_truth(
            as_of=date.today(), protocols=result["validation_protocols"]
        )
        result["pilot_preflight"]=build_preflight(
            as_of=date.today(),
            protocols=result["validation_protocols"],
            sources=result["freight_data_readiness"],
            rehearsal=result["synthetic_rehearsals"],
            ground=result["invoice_ground_truth"],
        )
        result["cfs_market_audit"]=build_market_audit(
            as_of=date.today(), protocols=result["validation_protocols"]
        )
        result["cfs_source_byte_readiness"]=build_cfs_byte_readiness(as_of=date.today())
        result["cfs_industry_quality"]=build_cfs_industry_readiness(as_of=date.today())
        result["recommended_next_actions"]=priority_actions(result)
        result["source_context"]={
            "revision_scope":"REPOSITORY_PYTHON_MODULES",
            "hosted_Floot_API_executed":False,
            "production_database_access":False,
            "externally_authenticated_financial_authority":False,
            "simulated_company_customer_count":3,
            "historical_findings_automatically_closed":0,
            "lab_execution_not_production_certification":True
        }
        return result


